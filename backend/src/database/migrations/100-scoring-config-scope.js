/**
 * 100 — scope + lifecycle on the scoring config table
 * (docs/plans/per-campaign-lead-scoring.md §9, PR C).
 *
 * Today the table is one flat global sequence: `version` is a bare INTEGER
 * PRIMARY KEY (091-consumer-enrichment.js:213-220) and the reader takes the
 * global maximum (consumerScoringService.js getActiveScoringConfig). This
 * migration gives a row a SCOPE and a LIFECYCLE without touching its identity.
 *
 * WHY `version` STAYS THE PK. A row's version IS its identity at every scope,
 * which keeps the stamp on every scored row (`scoredConfigVersion`, written by
 * consumerScoringService and leadScoringService) a single unambiguous integer.
 * No composite keys, no change to how a stored breakdown is read back.
 *
 * NO FOREIGN KEY ON `campaignId` — snapshot semantics (§9). Campaigns can be
 * permanently deleted while their prospects survive with `campaignId` nulled
 * (014-add-cascade-rules.js). ON DELETE CASCADE would destroy version rows
 * still stamped on surviving leads, breaking the invariant that every stored
 * breakdown stays interpretable; SET NULL is worse, because campaignId NULL
 * *means* global scope — it would silently promote a dead campaign's bespoke
 * config to global. A bare UUID does neither: the rows become unreachable
 * history, every historical stamp still resolves, and leads whose campaign
 * was deleted fall through to the global step.
 *
 * `status` DEFAULTS TO 'approved' SO EXISTING ROWS GRANDFATHER. They are live
 * today; a default of 'draft' would blank the resolution for everyone at the
 * instant this runs.
 *
 * VERSION ALLOCATION BECOMES REAL DDL. Each migration hand-allocated
 * MAX(version)+1 (094-scoring-recency-anchor.js:35-41) — a pattern two
 * concurrent RUNTIME writers (an AI draft and an admin approval, §8) would
 * race. From here every writer omits `version` and lets the database assign it.
 *
 * Owned transaction + catalog guards + idempotent, like 091/093/095: the
 * runner executes migrations on pool connections and is NOT atomic on its own,
 * and sync({force:true})-built test schemas already carry the model-declared
 * columns.
 */

/**
 * The identity attach is guarded on "does this column already have a
 * sequence", not on "is it already an identity column", because the two
 * environments arrive here differently:
 *
 *   - prod: `version INTEGER PRIMARY KEY`, no default → pg_get_serial_sequence
 *     is NULL → we attach GENERATED BY DEFAULT AS IDENTITY.
 *   - test: bootstrap.js runs sequelize.sync({force:true}) BEFORE migrations,
 *     and the model declares autoIncrement → Postgres already made it SERIAL →
 *     pg_get_serial_sequence is non-NULL → attaching identity would fail with
 *     "column already has a default". We skip and only setval.
 *
 * Both paths end with a column that allocates itself when a writer omits it,
 * which is the property the runtime depends on.
 */
const ATTACH_IDENTITY = `DO $$
BEGIN
  IF pg_get_serial_sequence('enrichment_scoring_configs', 'version') IS NULL THEN
    ALTER TABLE enrichment_scoring_configs
      ALTER COLUMN version ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$`;

/**
 * Push the sequence past the highest existing version. `is_called => true`
 * means the NEXT nextval() returns MAX+1, so the first runtime insert cannot
 * collide with a hand-allocated historical row (093 seeds v1, 094 appends v2,
 * 095 appends v3).
 *
 * COALESCE(MAX(version), 0) + guard: setval rejects 0 on a sequence whose
 * MINVALUE is 1, so an empty table sets 1 with is_called => false instead —
 * i.e. "the first value handed out is 1".
 */
const SETVAL_SEQUENCE = `DO $$
DECLARE
  seq TEXT := pg_get_serial_sequence('enrichment_scoring_configs', 'version');
  hi  BIGINT;
BEGIN
  IF seq IS NULL THEN RETURN; END IF;
  SELECT COALESCE(MAX(version), 0) INTO hi FROM enrichment_scoring_configs;
  IF hi > 0 THEN
    PERFORM setval(seq, hi, true);
  ELSE
    PERFORM setval(seq, 1, false);
  END IF;
END $$`;

